// Regenerates app/sw.js with a precache list + content hash. Run: node tools/build-sw.mjs
import fs from 'fs'; import path from 'path'; import crypto from 'crypto';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '../app');
const files = [];
const walk = (d) => { for (const f of fs.readdirSync(d)) { const p = path.join(d, f); if (fs.statSync(p).isDirectory()) walk(p); else if (!/sw\.js$|\.DS_Store/.test(f)) files.push(path.relative(root, p).split(path.sep).join('/')); } };
walk(root);
const h = crypto.createHash('sha1'); for (const f of files.sort()) h.update(f).update(fs.readFileSync(path.join(root, f)));
const ver = h.digest('hex').slice(0, 10);
const sw = `// Generated by tools/build-sw.mjs — offline support for Lari Studio
const CACHE = 'lari-${ver}';
const FILES = ${JSON.stringify(['./', ...files])};
self.addEventListener('install', (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener('activate', (e) => { e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((r) => r || fetch(e.request).then((res) => { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(e.request, copy)); return res; }).catch(() => caches.match('./'))));
});
`;
fs.writeFileSync(path.join(root, 'sw.js'), sw);
console.log('sw.js', ver, files.length, 'files');
